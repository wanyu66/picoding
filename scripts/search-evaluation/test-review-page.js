const { chromium } = require('playwright')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const assert = require('node:assert/strict')
;(async () => {
  process.chdir(path.resolve(__dirname, '../..'))
  require('node:fs').mkdirSync('.runtime', { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' })
  const context = await browser.newContext({ viewport: { width: 1350, height: 950 }, acceptDownloads: true })
  const page = await context.newPage(), errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto(pathToFileURL(path.resolve('scripts/search-evaluation/datasets/local-2026-09-23/review.html')).href)
    assert.equal(await page.locator('#queries button').count(), 64)
    assert.equal(await page.locator('#candidates article').count(), 8)
    await page.locator('#finish').click()
    assert.match(await page.locator('#message').textContent(), /标注者/)
    await page.locator('#reviewer').fill('SYNTHETIC_UI_TEST_NOT_A_HUMAN_LABEL')
    await page.locator('#finish').click()
    assert.match(await page.locator('#message').textContent(), /每篇候选/)
    // These scores exist only in this ephemeral browser context, never in the real judgment files.
    for (let i = 0; i < 8; i++) await page.locator('#candidates select').nth(i).selectOption(i === 0 ? '3' : '0')
    await page.locator('#answerability').selectOption('answerable')
    await page.locator('#reviewed').check()
    await page.locator('#finish').click()
    assert.match(await page.locator('#progress').textContent(), /^1 \/ 64/)
    const downloadPromise = page.waitForEvent('download')
    await page.locator('#export').click()
    const download = await downloadPromise, stream = await download.createReadStream(), chunks = []
    for await (const chunk of stream) chunks.push(chunk)
    const payload = Buffer.concat(chunks), rows = payload.toString('utf8').trim().split('\n').map(JSON.parse)
    assert.equal(rows.length, 64); assert.equal(rows[0].review.status, 'human_reviewed')
    assert.equal(rows.filter(q => q.review.status === 'pending').length, 63)
    await page.locator('#import').setInputFiles({ name: 'synthetic-unit-draft.jsonl', mimeType: 'application/json', buffer: payload })
    assert.match(await page.locator('#message').textContent(), /已导入/)
    await page.reload()
    assert.match(await page.locator('#progress').textContent(), /^1 \/ 64/)
    await page.evaluate(() => localStorage.clear())
    await page.reload()
    assert.match(await page.locator('#progress').textContent(), /^0 \/ 64/)
    await page.screenshot({ path: '.runtime/search-review-desktop.png', fullPage: false })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: '.runtime/search-review-mobile.png', fullPage: false })
    assert.deepEqual(errors, [])
    console.log('UI verified: 64 queries, 8 candidates, incomplete-review guards, export/import, reload persistence, mobile width; synthetic scores discarded')
  } finally { await context.close(); await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
